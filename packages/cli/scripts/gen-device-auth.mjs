#!/usr/bin/env node
// The CLI ships zero runtime dependencies, so the shared device flow from
// packages/device-auth is compiled in as src/device-auth.generated.ts.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "..", "device-auth", "src", "index.ts");
const output = join(root, "src", "device-auth.generated.ts");

if (!existsSync(source)) {
  // Building outside the monorepo: keep the committed copy.
  if (existsSync(output)) process.exit(0);
  throw new Error(`device-auth source not found at ${source}`);
}
const generated = `// Generated by scripts/gen-device-auth.mjs from packages/device-auth/src/index.ts. Do not edit.\n${readFileSync(source, "utf8")}`;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated) {
    console.error("device-auth copy is stale; run node packages/cli/scripts/gen-device-auth.mjs");
    process.exit(1);
  }
} else if (!existsSync(output) || readFileSync(output, "utf8") !== generated) {
  writeFileSync(output, generated);
}
