#!/usr/bin/env node
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const cli = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = join(cli, "..");
const release = readFileSync(join(cli, "BINARY_RELEASE"), "utf8").trim();
const publicKey = readFileSync(join(cli, "BINARY_SIGNING_PUBKEY.pub"), "utf8");
const releaseBase = "https://github.com/JuliusBrussee/caveman/releases/download";
const source = join(publicRoot, "shared", "binary-installer", "installer.mjs");
const generated = `// Generated by public/cli/scripts/gen-wedge-installer.mjs. Do not edit.
export const BINARY_RELEASE = ${JSON.stringify(release)};
export const BINARY_RELEASE_BASE_DEFAULT = ${JSON.stringify(releaseBase)};
export const BINARY_SIGNING_PUBKEY = ${JSON.stringify(publicKey)};
`;

for (const target of [
  join(publicRoot, "shared", "binary-installer"),
  join(publicRoot, "mcp", "bin"),
  join(publicRoot, "shrink", "bin"),
]) {
  if (!existsSync(target)) continue;
  writeFileSync(join(target, "release.generated.mjs"), generated);
  if (target !== join(publicRoot, "shared", "binary-installer")) {
    copyFileSync(source, join(target, "binary-installer.generated.mjs"));
  }
}
console.log(`generated standalone wedge installers for ${release}`);
